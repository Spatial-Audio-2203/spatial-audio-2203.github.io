export function paperUrl(p) { return p.doi ? 'https://doi.org/' + p.doi : p.publisher || (p.arxiv ? 'https://arxiv.org/abs/' + p.arxiv : p.source); }
export function bibtex(p) {
  const type = p.type === 'journal' ? 'article' : p.type === 'conference' ? 'inproceedings' : p.type === 'chapter' ? 'incollection' : 'misc';
  const field = p.type === 'journal' ? 'journal' : ['conference','chapter'].includes(p.type) ? 'booktitle' : 'howpublished';
  const fields = [['title',p.title],['author',p.authors.join(' and ')],[field,p.venue],['year',p.year],['volume',p.volume],['number',p.issue],['pages',p.pages],['doi',p.doi]];
  if (p.arxiv) fields.push(['eprint',p.arxiv],['archivePrefix','arXiv']);
  if (p.type === 'abstract') fields.push(['note','Meeting abstract']);
  if (p.type === 'conference' && p.number) fields.push(['note','Convention paper ' + p.number]);
  if (p.type === 'patent' || p.type === 'software') fields.push(['note',p.number]);
  fields.push(['url',paperUrl(p)]);
  return '@' + type + '{' + p.id.replace(/[^a-zA-Z0-9]/g,'') + p.year + ',\n' + fields.filter(([,v])=>v !== undefined && v !== '').map(([k,v])=>'  ' + k + ' = {' + v + '}').join(',\n') + '\n}';
}
